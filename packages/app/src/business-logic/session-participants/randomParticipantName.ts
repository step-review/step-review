/** A random fantasy name, e.g. "Amber Griffin". */
export default function randomParticipantName(): string {
  return `${randomItem(adjectives)} ${randomItem(creatures)}`;
}

function randomItem(items: string[]): string {
  return items[Math.floor(Math.random() * items.length)]!;
}
