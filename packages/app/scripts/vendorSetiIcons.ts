import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

/**
 * Copies VS Code's Seti file icon theme into `vendor/seti`: the icon font, the
 * theme's file associations, VS Code's language associations (the theme maps
 * most files through their language), and the licenses. Run it with a VS Code
 * release tag, e.g. `node scripts/vendorSetiIcons.ts 1.143.1`.
 */
const vscodeTag = process.argv[2];
if (!vscodeTag) {
  throw new Error("Pass a VS Code release tag, e.g. 1.143.1.");
}
const vendorDirectory = fileURLToPath(
  new URL("../vendor/seti/", import.meta.url),
);
const rawUrl = (repository: string, ref: string, path: string) =>
  `https://raw.githubusercontent.com/${repository}/${ref}/${path}`;

async function download(url: string): Promise<Response> {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url}: ${response.status}`);
  }
  return response;
}

interface IconTheme {
  iconDefinitions: Record<
    string,
    { fontCharacter: string; fontColor?: string }
  >;
  file: string;
  fileNames: Record<string, string>;
  fileExtensions: Record<string, string>;
  languageIds: Record<string, string>;
  light: Omit<IconTheme, "iconDefinitions" | "light">;
}

interface ExtensionManifest {
  contributes?: {
    languages?: { id: string; extensions?: string[]; filenames?: string[] }[];
  };
}

await mkdir(vendorDirectory, { recursive: true });
const themeUrl = (path: string) =>
  rawUrl("microsoft/vscode", vscodeTag, `extensions/theme-seti/${path}`);

const iconTheme = (await (
  await download(themeUrl("icons/vs-seti-icon-theme.json"))
).json()) as IconTheme;
await writeFile(
  `${vendorDirectory}setiIconTheme.json`,
  `${JSON.stringify(
    {
      iconDefinitions: iconTheme.iconDefinitions,
      file: iconTheme.file,
      fileNames: iconTheme.fileNames,
      fileExtensions: iconTheme.fileExtensions,
      languageIds: iconTheme.languageIds,
      light: iconTheme.light,
    },
    null,
    2,
  )}\n`,
);
await writeFile(
  `${vendorDirectory}seti.woff`,
  Buffer.from(
    await (await download(themeUrl("icons/seti.woff"))).arrayBuffer(),
  ),
);

// Only the languages the theme has icons for.
const languageAssociations = {
  fileNames: {} as Record<string, string>,
  fileExtensions: {} as Record<string, string>,
};
const extensionDirectories = (await (
  await download(
    `https://api.github.com/repos/microsoft/vscode/contents/extensions?ref=${vscodeTag}`,
  )
).json()) as { name: string; type: string }[];
for (const directory of extensionDirectories) {
  if (directory.type !== "dir") {
    continue;
  }
  const response = await fetch(
    rawUrl(
      "microsoft/vscode",
      vscodeTag,
      `extensions/${directory.name}/package.json`,
    ),
  );
  // Some directories hold shared code rather than an extension.
  if (!response.ok) {
    continue;
  }
  const extensionManifest = (await response.json()) as ExtensionManifest;
  for (const language of extensionManifest.contributes?.languages ?? []) {
    if (!(language.id in iconTheme.languageIds)) {
      continue;
    }
    for (const fileName of language.filenames ?? []) {
      languageAssociations.fileNames[fileName.toLowerCase()] ??= language.id;
    }
    for (const extension of language.extensions ?? []) {
      languageAssociations.fileExtensions[
        extension.replace(/^\./u, "").toLowerCase()
      ] ??= language.id;
    }
  }
}
await writeFile(
  `${vendorDirectory}vscodeLanguages.json`,
  `${JSON.stringify(languageAssociations, null, 2)}\n`,
);

const setiCommit = (
  (await (await download(themeUrl("cgmanifest.json"))).json()) as {
    registrations: { component: { git: { commitHash: string } } }[];
  }
).registrations[0]!.component.git.commitHash;
await writeFile(
  `${vendorDirectory}LICENSE-vscode.txt`,
  await (
    await download(rawUrl("microsoft/vscode", vscodeTag, "LICENSE.txt"))
  ).text(),
);
await writeFile(
  `${vendorDirectory}LICENSE-seti-ui.md`,
  await (
    await download(rawUrl("jesseweed/seti-ui", setiCommit, "LICENSE.md"))
  ).text(),
);
await writeFile(
  `${vendorDirectory}README.md`,
  [
    "# Seti file icons",
    "",
    `VS Code's Seti file icon theme, from VS Code ${vscodeTag} (MIT), based on`,
    `[Seti UI](https://github.com/jesseweed/seti-ui) at \`${setiCommit}\` (MIT).`,
    "Generated by `scripts/vendorSetiIcons.ts`; don't edit by hand.",
    "",
  ].join("\n"),
);
